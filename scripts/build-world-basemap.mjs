// Generate src/components/map/world-land.ts — the inline SVG basemap for /map.
//
// Source geometry: Natural Earth 110m "land" (public domain / no copyright),
// fetched as GeoJSON from the official natural-earth-vector repository:
// https://github.com/nvkelso/natural-earth-vector (geojson/ne_110m_land.geojson)
//
// The polygons are projected with a plain equirectangular projection onto a
// 1000-unit-wide viewBox, cropped to latitudes [LAT_MIN, LAT_MAX] (drops
// Antarctica — no cities there — and empty Arctic ocean), rounded to one
// decimal, and emitted as a single SVG path string. Keep LAT_MIN/LAT_MAX in
// sync with src/components/map/projection.ts (the generated file exports the
// values the projection helpers import).
//
// Run: node scripts/build-world-basemap.mjs
// Set NE_110M_LAND=/path/to/ne_110m_land.geojson to use a local copy.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'components', 'map', 'world-land.ts');

const VIEW_W = 1000;
const LAT_MAX = 74; // northernmost city (Reykjavik area) + margin
const LAT_MIN = -56; // Cape Horn; drops Antarctica
const VIEW_H = Number(((VIEW_W * (LAT_MAX - LAT_MIN)) / 360).toFixed(1));

// Rings smaller than this (in projected units²) are dropped — sub-pixel
// islands that only add bytes at the map's rendered size.
const MIN_RING_AREA = 2;

async function loadGeoJson() {
  const envPath = process.env.NE_110M_LAND;
  if (envPath) return JSON.parse(readFileSync(envPath, 'utf8'));
  const cacheDir = join(root, 'node_modules', '.cache', 'natural-earth');
  const cached = join(cacheDir, 'ne_110m_land.geojson');
  if (!existsSync(cached)) {
    console.log('Downloading Natural Earth 110m land GeoJSON (~140 KB)...');
    mkdirSync(cacheDir, { recursive: true });
    const res = await fetch(
      'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
    );
    if (!res.ok) throw new Error(`Natural Earth download failed: HTTP ${res.status}`);
    writeFileSync(cached, await res.text());
  }
  return JSON.parse(readFileSync(cached, 'utf8'));
}

const projectX = (lng) => ((lng + 180) / 360) * VIEW_W;
const projectY = (lat) => ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * VIEW_H;

// Shoelace area of a projected ring (absolute value).
function ringArea(points) {
  let sum = 0;
  for (let i = 0; i < points.length; i += 1) {
    const [x1, y1] = points[i];
    const [x2, y2] = points[(i + 1) % points.length];
    sum += x1 * y2 - x2 * y1;
  }
  return Math.abs(sum / 2);
}

function ringToPath(ring) {
  // Drop rings entirely outside the latitude crop (Antarctica).
  if (ring.every(([, lat]) => lat < LAT_MIN)) return null;

  const projected = [];
  for (const [lng, lat] of ring) {
    const clampedLat = Math.min(LAT_MAX, Math.max(LAT_MIN, lat));
    const x = Number(projectX(lng).toFixed(1));
    const y = Number(projectY(clampedLat).toFixed(1));
    const prev = projected[projected.length - 1];
    if (prev && prev[0] === x && prev[1] === y) continue; // dedupe after rounding
    projected.push([x, y]);
  }
  if (projected.length < 3 || ringArea(projected) < MIN_RING_AREA) return null;
  return `M${projected.map(([x, y]) => `${x} ${y}`).join('L')}Z`;
}

const geojson = await loadGeoJson();
const paths = [];
let ringCount = 0;
let dropped = 0;
for (const feature of geojson.features) {
  const { type, coordinates } = feature.geometry;
  const polygons = type === 'Polygon' ? [coordinates] : coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      ringCount += 1;
      const path = ringToPath(ring);
      if (path) paths.push(path);
      else dropped += 1;
    }
  }
}

const landPath = paths.join('');

const banner = `// Generated by scripts/build-world-basemap.mjs — do not edit by hand.
//
// Geometry: Natural Earth 1:110m "land" (public domain, naturalearthdata.com),
// via https://github.com/nvkelso/natural-earth-vector
// Projection: equirectangular, cropped to latitudes [${LAT_MIN}, ${LAT_MAX}].

/** SVG viewBox width of the basemap. */
export const VIEW_W = ${VIEW_W};
/** SVG viewBox height of the basemap. */
export const VIEW_H = ${VIEW_H};
/** Northern latitude edge of the map crop. */
export const LAT_MAX = ${LAT_MAX};
/** Southern latitude edge of the map crop. */
export const LAT_MIN = ${LAT_MIN};

/** All land as a single SVG path (equirectangular, ${VIEW_W}×${VIEW_H} viewBox). */
export const LAND_PATH =
`;

const chunks = landPath.match(/.{1,2000}/g) ?? [];
const literal = chunks.map((c) => `  '${c}'`).join(' +\n');
writeFileSync(outFile, `${banner}${literal};\n`);

const kb = (Buffer.byteLength(landPath) / 1024).toFixed(1);
console.log(
  `Wrote ${paths.length}/${ringCount} rings (${dropped} dropped), path ${kb} KB -> src/components/map/world-land.ts`
);
